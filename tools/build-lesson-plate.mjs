/* =====================================================================
   NAVIDIX — lesson plates and share cards, from a source frame.

   Every lesson's plate is a frame generated by an image model. This tool
   takes that frame and produces the three files a lesson actually ships:

     lessons/<id>.jpg     2000×857 (21:9)  the plate at the head of the page
     lessons/<id>.webp    the same, smaller
     og-<id>.png          1200×630         the share card, with the title on it

   It crops rather than squashes — centre by default, or biased with
   `focus` when the subject does not sit in the middle of the source. The
   share card puts the title over the same frame behind a scrim, so what
   gets posted to Telegram is the lesson's own picture and not a
   different one.

   Everything runs through a headless Chromium because nothing else on
   this machine can write JPEG or WebP; the browser does both.

       node tools/build-lesson-plate.mjs                 # all of them
       node tools/build-lesson-plate.mjs video-motion    # one

   Sources live in tools/plates/<id>.png and are not committed — they are
   the raw model output, and the repository ships the cropped result.
   Needs playwright (npm i playwright).
   ===================================================================== */
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'tools', 'plates');
const font = fs.readFileSync(path.join(ROOT, 'assets/estedad-var.woff2')).toString('base64');

/* id → what to write. `focus` is the point of the source that must stay
   in shot, as a fraction: .5/.5 is the centre. */
const PLATES = {
  'light-composition': {
    og: 'og-light.png', focus: [.5, .45],
    title: 'نور و ترکیب‌بندی:<br>چگونه یک قاب، <span>حس</span> می‌سازد',
    sub: 'قسمت دوم · آموزش هوش مصنوعی کاربردی'
  },
  'idea-to-final': {
    og: 'og-pipeline.png', focus: [.5, .5],
    title: 'از ایده تا نمای نهایی:<br>هفت مرحله‌ای که <span>ترتیب</span>شان همه‌چیز است',
    sub: 'قسمت سوم · آموزش هوش مصنوعی کاربردی'
  },
  'video-motion': {
    og: 'og-motion.png', focus: [.5, .5],
    title: 'پرامپت‌نویسی ویدیو:<br>از قاب ثابت تا <span>حرکت</span> کنترل‌شده',
    sub: 'قسمت چهارم · آموزش هوش مصنوعی کاربردی'
  },
  /* the three worked examples inside the light lesson: one subject, one
     room, three lighting and framing decisions. 16:9, no share card. */
  'light-a': { ratio: [16, 9], focus: [.5, .5] },
  'light-b': { ratio: [16, 9], focus: [.5, .5] },
  'light-c': { ratio: [16, 9], focus: [.5, .5] }
};

const pinned = process.env.PLAYWRIGHT_BROWSERS_PATH || '/opt/pw-browsers';
const found = fs.existsSync(pinned)
  ? fs.readdirSync(pinned).filter((d) => /^chromium-/.test(d))
      .map((d) => path.join(pinned, d, 'chrome-linux/chrome'))
      .filter((p) => fs.existsSync(p))[0]
  : null;
const browser = await chromium.launch(found ? { executablePath: found } : {});
const page = await browser.newPage({ viewport: { width: 100, height: 100 } });

/* One canvas pass: cover-crop the source into w×h around the focus point,
   then hand back both encodings. object-fit: cover, done by hand, because
   a canvas has no such property. */
async function crop(b64, w, h, focus) {
  return page.evaluate(async ([src, w, h, fx, fy]) => {
    const img = new Image();
    img.src = 'data:image/png;base64,' + src;
    await img.decode();
    const s = Math.max(w / img.width, h / img.height);
    const dw = img.width * s, dh = img.height * s;
    const c = document.createElement('canvas');
    c.width = w; c.height = h;
    const g = c.getContext('2d');
    g.imageSmoothingQuality = 'high';
    g.drawImage(img, (w - dw) * fx, (h - dh) * fy, dw, dh);
    return { jpg: c.toDataURL('image/jpeg', .88), webp: c.toDataURL('image/webp', .84),
             png: c.toDataURL('image/png') };
  }, [b64, w, h, focus[0], focus[1]]);
}

/* the share card: the same frame, a scrim, and the title over it */
async function card(b64, spec) {
  const w = 1200, h = 630;
  const bg = (await crop(b64, w, h, spec.focus)).png;
  const p = await browser.newPage({ viewport: { width: w, height: h } });
  await p.setContent(`<!doctype html><meta charset="utf-8"><style>
@font-face{font-family:'Estedad';src:url(data:font/woff2;base64,${font})format('woff2');font-weight:100 900}
*{margin:0;padding:0;box-sizing:border-box}
html,body{width:${w}px;height:${h}px;overflow:hidden;background:#07090C}
.card{position:relative;width:${w}px;height:${h}px;overflow:hidden}
.card img{position:absolute;inset:0;width:100%;height:100%;object-fit:cover}
/* the scrim: heavy under the type, gone on the far side, so the picture
   is still a picture and the words are still readable */
.scrim{position:absolute;inset:0;background:
  linear-gradient(to left, rgba(5,7,11,.94) 0%, rgba(5,7,11,.86) 38%, rgba(5,7,11,.34) 66%, rgba(5,7,11,.12) 100%),
  linear-gradient(to top, rgba(5,7,11,.5), transparent 46%)}
.tag{position:absolute;right:${w * .05}px;top:${h * .18}px;width:${w * .56}px;
  text-align:right;direction:rtl;font-family:Estedad,sans-serif;color:#EDF2FA}
.tag span{color:#E5202A}
</style>
<div class="card">
  <img src="${bg}" alt="" />
  <div class="scrim"></div>
  <div class="tag">
    <div style="font-size:${h * .026}px;letter-spacing:.24em;color:#B9C0C8;font-family:ui-monospace,monospace">
      NAVIDIX &nbsp;·&nbsp; TRAINING</div>
    <div style="font-size:${h * .07}px;line-height:1.55;font-weight:800;margin-top:${h * .04}px;
      text-shadow:0 2px 18px rgba(0,0,0,.8)">${spec.title}</div>
    <div style="font-size:${h * .032}px;line-height:1.9;color:#9AA3AE;margin-top:${h * .045}px">
      ${spec.sub}</div>
  </div>
</div>`, { waitUntil: 'load' });
  await p.evaluate(() => document.fonts.ready);
  const png = await p.screenshot({ type: 'png' });
  await p.close();
  return png;
}

const only = process.argv[2];
for (const id of (only ? [only] : Object.keys(PLATES))) {
  const spec = PLATES[id];
  if (!spec) { console.error('no plate called ' + id); process.exitCode = 1; continue; }
  const src = path.join(SRC, id + '.png');
  if (!fs.existsSync(src)) { console.error('missing source: ' + src); process.exitCode = 1; continue; }
  const b64 = fs.readFileSync(src).toString('base64');

  const [rw, rh] = spec.ratio || [21, 9];
  const W = 2000, H = Math.round(W * rh / rw);
  const out = await crop(b64, W, H, spec.focus);
  const bin = (u) => Buffer.from(u.slice(u.indexOf(',') + 1), 'base64');
  fs.writeFileSync(path.join(ROOT, 'lessons', id + '.jpg'), bin(out.jpg));
  fs.writeFileSync(path.join(ROOT, 'lessons', id + '.webp'), bin(out.webp));
  const files = ['lessons/' + id + '.jpg', 'lessons/' + id + '.webp'];

  if (spec.og) {
    fs.writeFileSync(path.join(ROOT, spec.og), await card(b64, spec));
    files.push(spec.og);
  }
  for (const f of files) {
    console.log(f.padEnd(32), W + '×' + H, (fs.statSync(path.join(ROOT, f)).size / 1024).toFixed(1) + ' KB');
  }
}
await browser.close();
