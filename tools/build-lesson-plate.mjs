/* =====================================================================
   NAVIDIX — drawn lesson plates.

   Most lessons carry a plate generated by an image model. Two do not:
   these are drawn, in the browser, out of the same geometry the lessons'
   own diagrams use. That is not a fallback dressed up as a choice — a
   lesson about where the light comes from, and a lesson about the order
   of the seven stages, can both state their own claim without borrowing
   a photograph. The caption under each says plainly that it is drawn.

   Every plate writes three files from one composition:

     lessons/<id>.jpg     1600×685   the plate at the head of the lesson
     lessons/<id>.webp    1600×685   the same, smaller
     <og>                 1200×630   the share card, titled

   WebP has no encoder on this machine, so the page re-encodes its own
   screenshot through a canvas — Chromium writes WebP even when the
   command line cannot.

       node tools/build-lesson-plate.mjs            # all of them
       node tools/build-lesson-plate.mjs idea-to-final

   Needs playwright (npm i playwright); the browser is already on the box
   at PLAYWRIGHT_BROWSERS_PATH.
   ===================================================================== */
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const font = fs.readFileSync(path.join(ROOT, 'assets/vazirmatn-var.woff2')).toString('base64');

/* ---------------------------------------------------------------------
   the light lesson: one key behind one subject
   ------------------------------------------------------------------ */

/* The subject, at plate scale. r is the head's radius and every other
   measurement is a multiple of it, so the bust can be moved and resized
   as one number — the same rule the diagram file keeps to. */
function bust(cx, base, r) {
  const hy = base - r * 3.15;
  return `
    <ellipse cx="${cx}" cy="${hy}" rx="${r}" ry="${r * 1.18}"/>
    <rect x="${cx - .42 * r}" y="${hy + .7 * r}" width="${.84 * r}" height="${r}"/>
    <path d="M${cx - 2.45 * r} ${base}
             C${cx - 2.3 * r} ${hy + 2 * r},${cx - 1.05 * r} ${hy + 1.5 * r},${cx} ${hy + 1.5 * r}
             C${cx + 1.05 * r} ${hy + 1.5 * r},${cx + 2.3 * r} ${hy + 2 * r},${cx + 2.45 * r} ${base}Z"/>`;
}
/* The lit edge, as one unbroken stroke: crown, temple, jaw, neck,
   shoulder. Drawn in separate pieces it picks up a corner at the neck
   that reads as a drawing error rather than as light. */
function rim(cx, base, r) {
  const hy = base - r * 3.15;
  return `M${cx} ${hy - r * 1.18}
          A${r} ${r * 1.18} 0 0 1 ${cx + .42 * r} ${hy + 1.071 * r}
          V${hy + 1.5 * r}
          C${cx + 1.05 * r} ${hy + 1.5 * r},${cx + 2.3 * r} ${hy + 2 * r},${cx + 2.45 * r} ${base}`;
}

/* The subject stands on the left third and the light comes from the far
   upper right, so the empty half of the frame is the half it is facing
   into — the lesson's own look-room rule, applied to its own plate. On
   the share card that same empty half is where the title goes. */
function lightArt(w, h, titled) {
  const cx = w * .27, base = h * 1.06, r = h * (titled ? .155 : .175);
  return {
    css: `
.sub{fill:#05070A}
.edge{fill:none;stroke:#EDF3FA;stroke-width:${Math.max(2, h * .0055)};stroke-linecap:round}
.glow{fill:none;stroke:rgba(237,243,250,.28);stroke-width:${h * .026};stroke-linecap:round;filter:blur(${h * .018}px)}
/* the source itself, at the far end of the beam: the plate then carries
   the whole sentence the lesson is about — lamp, throw, lit edge */
.src{position:absolute;border-radius:50%;background:#F4F8FD;
  box-shadow:0 0 ${h * .06}px ${h * .02}px rgba(233,244,255,.75),
             0 0 ${h * .3}px ${h * .1}px rgba(190,214,245,.16);}`,
    html: `
  ${titled ? '' : `<div class="thirds">
    <i class="v" style="left:${(w / 3).toFixed(1)}px"></i><i class="v" style="left:${(w * 2 / 3).toFixed(1)}px"></i>
    <i class="h" style="top:${(h / 3).toFixed(1)}px"></i><i class="h" style="top:${(h * 2 / 3).toFixed(1)}px"></i>
  </div>`}
  ${titled ? '' : `<div class="src" style="width:${h * .034}px;height:${h * .034}px;
    right:${w * .17}px;top:${h * .17}px"></div>`}
  <svg class="art" viewBox="0 0 ${w} ${h}">
    <g class="sub">${bust(cx, base, r)}</g>
    <path class="glow" d="${rim(cx, base, r)}"/>
    <path class="edge" d="${rim(cx, base, r)}"/>
  </svg>`
  };
}

/* ---------------------------------------------------------------------
   the pipeline lesson: seven frames on one rail

   The first station is an empty outline barely lit and the last is a
   finished frame with light inside it, so the plate says what the lesson
   says — the thing at the end exists because six stations came before
   it, in that order.
   ------------------------------------------------------------------ */
function pipeArt(w, h, titled) {
  const N = 7;
  const railY = h * (titled ? .8 : .63);
  const x0 = w * (titled ? .07 : .09), x1 = w * (titled ? .93 : .91);
  const at = (i) => x0 + (x1 - x0) * i / (N - 1);
  const wide = h * (titled ? .075 : .105);          /* the first frame */
  const grow = titled ? 2.1 : 2.6;                  /* the last, in units of the first */

  let boxes = '', pins = '';
  for (let i = 0; i < N; i++) {
    const t = i / (N - 1);
    const fw = wide * (1 + (grow - 1) * t), fh = fw * 9 / 16;
    const x = at(i) - fw / 2, y = railY - h * .045 - fh;
    const on = i === N - 1;
    boxes +=
      `<rect x="${x}" y="${y}" width="${fw}" height="${fh}" rx="${fw * .03}"
             fill="${on ? 'url(#lit)' : '#0A0D13'}"
             stroke="${on ? '#EDF3FA' : '#2B3441'}"
             stroke-width="${on ? Math.max(2, h * .004) : 1.2}"
             opacity="${(.34 + .66 * t).toFixed(3)}"/>` +
      `<line x1="${at(i)}" y1="${y + fh}" x2="${at(i)}" y2="${railY}"
             stroke="#2B3441" stroke-width="1" opacity="${(.3 + .5 * t).toFixed(2)}"/>`;
    pins +=
      `<circle cx="${at(i)}" cy="${railY}" r="${h * (on ? .011 : .007)}"
               fill="${on ? '#E5202A' : '#131820'}" stroke="${on ? '#E5202A' : '#39424E'}" stroke-width="1.4"/>`;
  }

  return {
    css: `.spark{position:absolute;border-radius:50%;background:#E5202A;
  box-shadow:0 0 ${h * .05}px ${h * .015}px rgba(229,32,42,.7);}`,
    html: `
  <svg class="art" viewBox="0 0 ${w} ${h}">
    <defs>
      <radialGradient id="lit" cx="50%" cy="42%">
        <stop offset="0%" stop-color="#EAF1FA" stop-opacity=".55"/>
        <stop offset="70%" stop-color="#8FA6C4" stop-opacity=".14"/>
        <stop offset="100%" stop-color="#0A0D13" stop-opacity="0"/>
      </radialGradient>
      <linearGradient id="rail" x1="0" x2="1">
        <stop offset="0%" stop-color="#2B3441" stop-opacity=".5"/>
        <stop offset="100%" stop-color="#E5202A" stop-opacity=".95"/>
      </linearGradient>
    </defs>
    <line x1="${x0 - h * .05}" y1="${railY}" x2="${x1 + h * .05}" y2="${railY}"
          stroke="url(#rail)" stroke-width="${Math.max(2, h * .0045)}"/>
    ${boxes}${pins}
  </svg>
  ${titled ? '' : `<div class="spark" style="width:${h * .018}px;height:${h * .018}px;
    left:${x0 - h * .05}px;top:${railY - h * .009}px"></div>`}`
  };
}

/* ---------------------------------------------------------------------
   the motion lesson: one frame, given time

   A push-in drawn as what it actually is — the same rectangle, sampled
   at five moments, each one a step larger and a step further along.
   Nothing here is a metaphor for movement; it is a movement, held still.
   ------------------------------------------------------------------ */
function motionArt(w, h, titled) {
  const N = 5;
  const cy = h * (titled ? .62 : .54);
  const x0 = w * (titled ? .1 : .12);
  const base = h * (titled ? .26 : .36);
  let frames = '';
  for (let i = 0; i < N; i++) {
    const t = i / (N - 1);
    const fw = base * (1 + 1.05 * t) * (16 / 9), fh = base * (1 + 1.05 * t);
    const cxi = x0 + w * (titled ? .3 : .42) * t;
    frames += `<rect x="${cxi - fw / 2}" y="${cy - fh / 2}" width="${fw}" height="${fh}" rx="3"
      fill="none" stroke="${i === N - 1 ? '#EDF3FA' : '#4A5665'}"
      stroke-width="${i === N - 1 ? Math.max(2, h * .004) : 1.3}"
      opacity="${(.2 + .8 * t).toFixed(3)}"/>`;
  }
  return {
    css: `.trail{position:absolute;border-radius:50%;background:#E5202A;
  box-shadow:0 0 ${h * .05}px ${h * .016}px rgba(229,32,42,.65);}`,
    html: `
  <svg class="art" viewBox="0 0 ${w} ${h}">${frames}</svg>
  ${titled ? '' : `<div class="trail" style="width:${h * .016}px;height:${h * .016}px;
    left:${x0}px;top:${cy - h * .008}px"></div>`}`
  };
}

