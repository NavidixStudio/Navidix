/* =====================================================================
   NAVIDIX — the plate for the light lesson.

   Every other lesson's plate is a frame generated by an image model. This
   one is drawn, in the browser, from the same geometry the lesson's own
   diagrams use — a single key behind a bust, a rim on the lit edge, and
   the thirds the lesson spends a section on. That is not a fallback: a
   lesson about where the light comes from should be able to show its own
   claim without borrowing a photograph, and the caption on the page says
   plainly that it is drawn.

   Writes three files, all from one composition:

     lessons/light-composition.jpg    1600×685   the plate
     lessons/light-composition.webp   1600×685   the same, smaller
     og-light.png                     1200×630   the share card, titled

   WebP has no encoder on this machine, so the page re-encodes its own
   screenshot through a canvas — Chromium can write WebP even when the
   command line cannot.

       node tools/build-lesson-plate.mjs

   Needs playwright (npm i playwright); the browser is already on the box
   at PLAYWRIGHT_BROWSERS_PATH.
   ===================================================================== */
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const font = fs.readFileSync(path.join(ROOT, 'assets/vazirmatn-var.woff2')).toString('base64');

/* The subject, at plate scale. r is the head's radius and every other
   measurement is a multiple of it, so the bust can be moved and resized
   as one number — the same rule the diagram file keeps to. */
function bust(cx, base, r) {
  const hy = base - r * 3.15;
  return `
    <ellipse cx="${cx}" cy="${hy}" rx="${r}" ry="${r * 1.18}"/>
    <rect x="${cx - .42 * r}" y="${hy + .7 * r}" width="${.84 * r}" height="${r}"/>
    <path d="M${cx - 2.45 * r} ${base}
             C${cx - 2.3 * r} ${hy + 2 * r},${cx - 1.05 * r} ${hy + 1.5 * r},${cx} ${hy + 1.5 * r}
             C${cx + 1.05 * r} ${hy + 1.5 * r},${cx + 2.3 * r} ${hy + 2 * r},${cx + 2.45 * r} ${base}Z"/>`;
}
/* The lit edge, as one unbroken stroke: crown, temple, jaw, neck,
   shoulder. Drawn in separate pieces it picks up a corner at the neck
   that reads as a drawing error rather than as light. */
function rim(cx, base, r) {
  const hy = base - r * 3.15;
  return `M${cx} ${hy - r * 1.18}
          A${r} ${r * 1.18} 0 0 1 ${cx + .42 * r} ${hy + 1.071 * r}
          V${hy + 1.5 * r}
          C${cx + 1.05 * r} ${hy + 1.5 * r},${cx + 2.3 * r} ${hy + 2 * r},${cx + 2.45 * r} ${base}`;
}

/* w/h are the plate's own pixels; the composition is written against them
   so the share card is the same picture rather than a crop of it. */
function page(w, h, title) {
  /* The subject stands on the left third and the light comes from the far
     upper right, so the empty half of the frame is the half it is facing
     into — the lesson's own look-room rule, applied to its own plate. On
     the share card that same empty half is where the title goes. */
  const cx = w * .27, base = h * 1.06, r = h * (title ? .155 : .175);
  return `<!doctype html><meta charset="utf-8"><style>
@font-face{font-family:'Vazirmatn';src:url(data:font/woff2;base64,${font})format('woff2');font-weight:100 900}
*{margin:0;padding:0;box-sizing:border-box}
html,body{width:${w}px;height:${h}px;overflow:hidden;background:#080A0E}
.plate{position:relative;width:${w}px;height:${h}px;overflow:hidden;
  background:
    radial-gradient(${h * 1.6}px ${h * 1.3}px at ${w * .84}px ${h * -.12}px, rgba(226,238,255,.22), transparent 64%),
    radial-gradient(${h * .7}px ${h * .7}px at ${w * .06}px ${h * .78}px, rgba(229,32,42,.15), transparent 68%),
    linear-gradient(168deg,#11151C 0%,#0A0D12 46%,#07090C 100%);}
/* The beam: one band of haze leaving the key, which is the only reason a
   viewer can tell where the light is standing. Feathered at both ends and
   blurred — a clipped wedge leaves a hard diagonal across the sky, which
   reads as a rendering seam rather than as light. */
.beam{position:absolute;inset:-20%;
  background:linear-gradient(104deg,
    transparent 16%, rgba(226,238,255,.13) 33%, rgba(226,238,255,.05) 48%, transparent 64%);
  filter:blur(${h * .05}px);}
.floor{position:absolute;left:0;right:0;bottom:0;height:${h * .3}px;
  background:linear-gradient(to top, rgba(226,238,255,.07), transparent);}
.thirds{position:absolute;inset:0}
.thirds i{position:absolute;background:rgba(226,238,255,.075)}
.thirds i.v{top:0;bottom:0;width:1px}
.thirds i.h{left:0;right:0;height:1px}
.grain{position:absolute;inset:0;opacity:.5;mix-blend-mode:overlay}
.vig{position:absolute;inset:0;
  background:radial-gradient(120% 120% at 50% 46%, transparent 42%, rgba(3,4,6,.86) 100%);}
svg.art{position:absolute;inset:0}
.sub{fill:#05070A}
.edge{fill:none;stroke:#EDF3FA;stroke-width:${Math.max(2, h * .0055)};stroke-linecap:round}
.glow{fill:none;stroke:rgba(237,243,250,.28);stroke-width:${h * .026};stroke-linecap:round;filter:blur(${h * .018}px)}
/* the source itself, at the far end of the beam: the plate then carries
   the whole sentence the lesson is about — lamp, throw, lit edge */
.src{position:absolute;border-radius:50%;background:#F4F8FD;
  box-shadow:0 0 ${h * .06}px ${h * .02}px rgba(233,244,255,.75),
             0 0 ${h * .3}px ${h * .1}px rgba(190,214,245,.16);}
.tag{position:absolute;font-family:Vazirmatn,sans-serif;color:#E4E7EA;direction:rtl}
</style>
<div class="plate">
  <div class="beam"></div>
  <div class="floor"></div>
  ${title ? '' : `<div class="thirds">
    <i class="v" style="left:${(w / 3).toFixed(1)}px"></i><i class="v" style="left:${(w * 2 / 3).toFixed(1)}px"></i>
    <i class="h" style="top:${(h / 3).toFixed(1)}px"></i><i class="h" style="top:${(h * 2 / 3).toFixed(1)}px"></i>
  </div>`}
  ${title ? '' : `<div class="src" style="width:${h * .034}px;height:${h * .034}px;
    right:${w * .17}px;top:${h * .17}px"></div>`}
  <svg class="art" viewBox="0 0 ${w} ${h}">
    <g class="sub">${bust(cx, base, r)}</g>
    <path class="glow" d="${rim(cx, base, r)}"/>
    <path class="edge" d="${rim(cx, base, r)}"/>
  </svg>
  <svg class="grain"><filter id="g"><feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="3"/>
    <feColorMatrix type="saturate" values="0"/></filter>
    <rect width="100%" height="100%" filter="url(#g)" opacity=".28"/></svg>
  <div class="vig"></div>
  ${title ? `
  <div class="tag" style="right:${w * .05}px;top:${h * .2}px;width:${w * .52}px;text-align:right">
    <div style="font-size:${h * .026}px;letter-spacing:.24em;color:#B9C0C8;font-family:ui-monospace,monospace">
      NAVIDIX &nbsp;·&nbsp; TRAINING</div>
    <div style="font-size:${h * .076}px;line-height:1.5;font-weight:800;margin-top:${h * .04}px">
      نور و ترکیب‌بندی:<br>چگونه یک قاب، <span style="color:#E5202A">حس</span> می‌سازد</div>
    <div style="font-size:${h * .032}px;line-height:1.9;color:#8C939B;margin-top:${h * .045}px">
      قسمت دوم · آموزش هوش مصنوعی کاربردی</div>
  </div>` : ''}
</div>`;
}

/* PLAYWRIGHT_BROWSERS_PATH holds a chromium that a differently-versioned
   playwright will not find by itself; point at it when it is there and
   fall back to whatever this playwright installed for itself. */
const pinned = (process.env.PLAYWRIGHT_BROWSERS_PATH || '/opt/pw-browsers');
const found = fs.existsSync(pinned)
  ? fs.readdirSync(pinned).filter(function (d) { return /^chromium-/.test(d); })
      .map(function (d) { return path.join(pinned, d, 'chrome-linux/chrome'); })
      .filter(function (p) { return fs.existsSync(p); })[0]
  : null;
const browser = await chromium.launch(found ? { executablePath: found } : {});

async function shoot(w, h, title) {
  const p = await browser.newPage({ viewport: { width: w, height: h }, deviceScaleFactor: 1 });
  await p.setContent(page(w, h, title), { waitUntil: 'load' });
  await p.evaluate(() => document.fonts.ready);
  const png = await p.screenshot({ type: 'png' });
  /* re-encode through a canvas: no webp or jpeg encoder exists outside
     the browser on this machine, and Chromium has both */
  const out = await p.evaluate(async (b64) => {
    const img = new Image();
    img.src = 'data:image/png;base64,' + b64;
    await img.decode();
    const c = document.createElement('canvas');
    c.width = img.width; c.height = img.height;
    c.getContext('2d').drawImage(img, 0, 0);
    return { jpg: c.toDataURL('image/jpeg', .86), webp: c.toDataURL('image/webp', .82) };
  }, png.toString('base64'));
  await p.close();
  const bin = (u) => Buffer.from(u.slice(u.indexOf(',') + 1), 'base64');
  return { png, jpg: bin(out.jpg), webp: bin(out.webp) };
}

const plate = await shoot(1600, 685, false);
fs.writeFileSync(path.join(ROOT, 'lessons/light-composition.jpg'), plate.jpg);
fs.writeFileSync(path.join(ROOT, 'lessons/light-composition.webp'), plate.webp);

const og = await shoot(1200, 630, true);
fs.writeFileSync(path.join(ROOT, 'og-light.png'), og.png);

await browser.close();
for (const f of ['lessons/light-composition.jpg', 'lessons/light-composition.webp', 'og-light.png']) {
  console.log(f, (fs.statSync(path.join(ROOT, f)).size / 1024).toFixed(1) + ' KB');
}
